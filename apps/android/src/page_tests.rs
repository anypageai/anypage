//! The text-input-test page, driven headlessly the way the Android host
//! drives it: taps, committed text, IME composition, keys, clipboard and
//! file answers, wheel, drops. Also checks the APK's copy of the package and
//! the field's pixels.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use anypage_engine::core::Status;
use anypage_engine::{HostResult, Image, Page, PageRequest, PointerResponse, TextRaster, Wake};
use anypage_runtime::{Data, Natives, Package, ScriptPage};

use crate::packages::{self, PageSource};

const PAGE: &str = "text-input-test";
// world rectangles from pages/text-input-test/main.luau
const FIELD: (f32, f32, f32, f32) = (0.0, 84.0, 720.0, 96.0);
const LOG: (f32, f32, f32, f32) = (0.0, 416.0, 720.0, 444.0);
const BUTTON_W: f32 = (720.0 - 10.0 * 4.0) / 5.0;
const ACCENT: [u8; 3] = [96, 156, 255];
const PRE: [u8; 3] = [255, 196, 92];
const FIELD_BG: [u8; 3] = [12, 14, 19];

fn text() -> Arc<TextRaster> {
    Arc::new(TextRaster::load().expect("a system font"))
}

fn wake() -> Wake {
    Arc::new(|| {})
}

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn source_dir() -> PathBuf {
    repo().join("pages").join(PAGE)
}

/// Where hand-made copies of packages used to live (now generated by Gradle).
fn assets_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("app/src/main/assets/pages")
}

fn load() -> ScriptPage {
    let pkg = Package::from_dir(&source_dir()).expect("package");
    ScriptPage::load(&pkg, &Natives::new(), text(), wake()).expect("load")
}

fn get(p: &mut ScriptPage, name: &str) -> Data {
    p.cell_value(name).unwrap_or_else(|| panic!("no cell {name}"))
}

fn text_of(p: &mut ScriptPage) -> String {
    get(p, "text").as_str().expect("text is a string").to_string()
}

fn log_of(p: &mut ScriptPage) -> Vec<String> {
    get(p, "log").items().iter().filter_map(|d| d.as_str().map(str::to_string)).collect()
}

fn button(i: usize) -> (f32, f32) {
    ((i as f32 - 1.0) * (BUTTON_W + 10.0) + BUTTON_W / 2.0, 260.0 + 36.0)
}

fn tap_field(p: &mut ScriptPage, x: f32) {
    assert_eq!(p.pointer_down(x, FIELD.1 + FIELD.3 / 2.0), PointerResponse::Handled);
    p.pointer_up();
}

/// The field panel's pixels at scale 1 (one pixel per world unit).
fn field_image(p: &mut ScriptPage) -> Arc<Image> {
    let cell = {
        let g = p.graph();
        p.spec().panels.iter().map(|x| x.cell).find(|c| g.label(*c) == "field.raster").expect("field panel")
    };
    let g = p.parts().0;
    let i = g.demand(cell);
    assert!(matches!(i.status, Status::Ready), "{:?}", i.status);
    let img = i.value.clone().expect("a value").downcast::<Image>().expect("an image");
    assert_eq!((img.w, img.h), (FIELD.2 as u32, FIELD.3 as u32));
    img
}

fn px(img: &Image, x: u32, y: u32) -> [u8; 3] {
    let i = ((y * img.w + x) * 4) as usize;
    [img.rgba[i], img.rgba[i + 1], img.rgba[i + 2]]
}

fn near(a: [u8; 3], b: [u8; 3], tol: i32) -> bool {
    a.iter().zip(b).all(|(x, y)| (*x as i32 - y as i32).abs() <= tol)
}

fn count_in(img: &Image, x0: u32, x1: u32, y0: u32, y1: u32, mut f: impl FnMut([u8; 3]) -> bool) -> usize {
    let mut n = 0;
    for y in y0..y1.min(img.h) {
        for x in x0..x1.min(img.w) {
            if f(px(img, x, y)) {
                n += 1;
            }
        }
    }
    n
}

/// The APK gets the repository's pages/ folder from Gradle (`syncPages`),
/// not from copies kept in app/src/main/assets that drift.
#[test]
fn the_apk_ships_the_pages_folder() {
    let gradle = std::fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("app/build.gradle.kts")).expect("app/build.gradle.kts");
    assert!(gradle.contains("register<SyncPages>(\"syncPages\")") && gradle.contains("\"../../pages\""), "the syncPages task is gone");
    assert!(gradle.contains("addGeneratedSourceDirectory(syncPages"), "syncPages is not wired into the assets");
    let copies: Vec<String> = std::fs::read_dir(assets_dir()).map(|rd| rd.flatten().map(|e| e.file_name().to_string_lossy().into_owned()).collect()).unwrap_or_default();
    assert!(copies.is_empty(), "packages copied by hand into app/src/main/assets/pages: {copies:?}");
    // the page loads the way the Android host loads assets
    let mut names: Vec<String> = std::fs::read_dir(source_dir()).expect("pages/text-input-test").flatten().map(|e| e.file_name().to_string_lossy().into_owned()).collect();
    names.sort();
    assert!(names.contains(&"page.json".to_string()) && names.contains(&"main.luau".to_string()), "{names:?}");
    let files: Vec<(String, Vec<u8>)> = names.iter().map(|n| (n.clone(), std::fs::read(source_dir().join(n)).unwrap())).collect();
    let mut loaded = packages::load(&PageSource::Assets { name: PAGE.into(), files }, text(), wake(), &Default::default());
    assert!(loaded.error.is_none(), "{:?}", loaded.error);
    assert!(loaded.summary.contains("com.anypage.text-input-test"), "{}", loaded.summary);
    loaded.page.shutdown();
}

#[test]
fn typing_composing_and_editing() {
    let mut p = load();
    assert_eq!(p.text_focus(), None);
    // keys go to the engine (not the field) before it has focus
    assert!(!p.key("a"));

    tap_field(&mut p, 40.0);
    let f0 = p.text_focus().expect("tapping the field gives text focus");
    assert!(f0.y >= FIELD.1 && f0.bottom() <= FIELD.1 + FIELD.3, "{f0:?}");

    p.text_input("hello");
    assert_eq!(text_of(&mut p), "hello");
    assert_eq!(get(&mut p, "caret"), Data::Num(5.0));
    let f1 = p.text_focus().unwrap();
    assert!(f1.x > f0.x + 40.0, "the caret moved right: {f0:?} -> {f1:?}");

    // IME composition: shown at the caret, not yet in the text
    p.ime_preedit("wor");
    assert_eq!(get(&mut p, "preedit"), Data::str("wor"));
    assert_eq!(text_of(&mut p), "hello");
    let f2 = p.text_focus().unwrap();
    assert!(f2.x > f1.x, "the IME window follows the composition");
    // commit, as the Android host does: end the preedit, then the text
    p.ime_preedit("");
    p.text_input("世界👍🏽");
    assert_eq!(text_of(&mut p), "hello世界👍🏽");
    assert_eq!(get(&mut p, "preedit"), Data::str(""));

    // grapheme-correct editing
    assert!(p.key("backspace"));
    assert_eq!(text_of(&mut p), "hello世界");
    assert!(p.key("left"));
    p.text_input("X");
    assert_eq!(text_of(&mut p), "hello世X界");
    assert!(p.key("home"));
    p.text_input(">");
    assert!(p.key("delete"));
    assert_eq!(text_of(&mut p), ">ello世X界");
    assert!(p.key("ctrl+right"));
    assert!(p.key("ctrl+backspace"));
    assert_eq!(text_of(&mut p), ">世X界", "ctrl+backspace removes the word");

    // clipboard
    assert!(p.key("ctrl+c"));
    assert_eq!(p.take_request(), Some(PageRequest::Copy(">世X界".into())));
    assert!(p.key("end"));
    assert!(p.key("ctrl+v"));
    assert_eq!(p.take_request(), Some(PageRequest::Paste));
    p.paste(" pasted");
    assert_eq!(text_of(&mut p), ">世X界 pasted");

    // committed text with a newline submits the line
    p.text_input("!\nnext");
    assert_eq!(text_of(&mut p), "next");
    assert!(log_of(&mut p).iter().any(|l| l == "enter: >世X界 pasted!"), "{:?}", log_of(&mut p));
    assert!(p.key("enter"));
    assert_eq!(text_of(&mut p), "");

    // escape and taps elsewhere end text focus; the composition is dropped
    tap_field(&mut p, 40.0);
    p.ime_preedit("ni");
    assert!(p.key("escape"));
    assert_eq!(p.text_focus(), None);
    assert_eq!(get(&mut p, "preedit"), Data::str(""));
    tap_field(&mut p, 40.0);
    assert!(p.text_focus().is_some());
    assert_eq!(p.pointer_down(700.0, 20.0), PointerResponse::Ignored, "a tap on the title lets the engine pan");
    assert_eq!(p.text_focus(), None);
    // without focus, text and composition are not taken
    p.text_input("lost");
    p.ime_preedit("lost");
    assert_eq!(text_of(&mut p), "");
    assert_eq!(get(&mut p, "preedit"), Data::str(""));
    assert_eq!(p.handler_errors, 0);
    p.shutdown();
}

#[test]
fn clipboard_files_drops_and_wheel() {
    let mut p = load();
    // Paste button with no field focus: the page asks, the answer is logged
    let (x, y) = button(2);
    assert_eq!(p.pointer_down(x, y), PointerResponse::Handled);
    assert_eq!(p.take_request(), Some(PageRequest::Paste));
    p.paste("clip");
    assert!(log_of(&mut p).contains(&"paste: 4 bytes".to_string()));

    // Open…: the host answers with the file
    let (x, y) = button(3);
    p.pointer_down(x, y);
    let id = match p.take_request() {
        Some(PageRequest::OpenFile { id, filters }) => {
            assert_eq!(filters, vec!["txt".to_string()]);
            id
        }
        other => panic!("{other:?}"),
    };
    p.host_result(id, HostResult::File { name: "a.txt".into(), bytes: Arc::new(b"hello".to_vec()) });
    assert_eq!(get(&mut p, "file"), Data::str("opened a.txt (5 bytes)"));
    // ... or the user cancels
    p.pointer_down(x, y);
    let Some(PageRequest::OpenFile { id, .. }) = p.take_request() else { panic!("open request") };
    p.host_result(id, HostResult::Cancelled);
    assert_eq!(get(&mut p, "file"), Data::str("open cancelled"));

    // Save…: the bytes are the field's text
    tap_field(&mut p, 40.0);
    p.text_input("note 筆記");
    let (x, y) = button(4);
    p.pointer_down(x, y);
    match p.take_request() {
        Some(PageRequest::SaveFile { id, name, bytes }) => {
            assert_eq!(name, "anypage-note.txt");
            assert_eq!(bytes.as_slice(), "note 筆記".as_bytes());
            p.host_result(id, HostResult::Saved { name: "anypage-note.txt".into() });
        }
        other => panic!("{other:?}"),
    }
    assert_eq!(get(&mut p, "file"), Data::str("saved anypage-note.txt (11 bytes)"));
    p.pointer_down(x, y);
    let Some(PageRequest::SaveFile { id, .. }) = p.take_request() else { panic!("save request") };
    p.host_result(id, HostResult::Failed("disk full".into()));
    assert_eq!(get(&mut p, "file"), Data::str("save failed: disk full"));

    // a dropped file
    p.file_drop("b.pdf", Arc::new(vec![1, 2, 3]));
    assert_eq!(get(&mut p, "file"), Data::str("dropped b.pdf (3 bytes)"));

    // the wheel scrolls the log; elsewhere the engine zooms
    for i in 0..30 {
        p.text_input(&format!("{i}\n"));
    }
    let (lx, ly) = (LOG.0 + 100.0, LOG.1 + 200.0);
    assert!(p.wheel(lx, ly, 0.0, 3.0));
    assert_eq!(get(&mut p, "scroll"), Data::Num(3.0));
    assert!(p.wheel(lx, ly, 0.0, -1.0));
    assert_eq!(get(&mut p, "scroll"), Data::Num(2.0));
    assert!(!p.wheel(360.0, 20.0, 0.0, 1.0));
    // drag scrolling
    assert_eq!(p.pointer_down(lx, ly), PointerResponse::Captured);
    p.pointer_drag(lx, ly + 28.0 * 4.0);
    p.pointer_up();
    assert_eq!(get(&mut p, "scroll"), Data::Num(6.0));

    // the semantic port
    let r = p.act(r#"{"action": "type", "params": {"text": "agent"}}"#);
    assert!(r.contains("agent"), "{r}");
    assert_eq!(p.handler_errors, 0);
    p.shutdown();
}

/// Collects what pages send to `page.log` (log target "anypage_page"),
/// from every test in this binary; tests look for their own markers.
mod captured {
    use std::sync::{Mutex, OnceLock};

    static LINES: Mutex<Vec<String>> = Mutex::new(Vec::new());

    struct Capture;
    impl log::Log for Capture {
        fn enabled(&self, m: &log::Metadata) -> bool {
            m.target() == "anypage_page"
        }
        fn log(&self, r: &log::Record) {
            if self.enabled(r.metadata()) {
                LINES.lock().unwrap_or_else(|p| p.into_inner()).push(r.args().to_string());
            }
        }
        fn flush(&self) {}
    }

    static CAPTURE: Capture = Capture;

    pub fn install() {
        static ONCE: OnceLock<()> = OnceLock::new();
        ONCE.get_or_init(|| {
            if log::set_logger(&CAPTURE).is_ok() {
                log::set_max_level(log::LevelFilter::Info);
            }
        });
    }

    pub fn lines() -> Vec<String> {
        LINES.lock().unwrap_or_else(|p| p.into_inner()).clone()
    }
}

#[test]
fn agents_cannot_break_the_field() {
    let mut p = load();
    // an agent may store any JSON value in the agent-writable "text"
    for (value, shows) in [("5", "5"), ("true", "true"), ("null", ""), ("{\"a\": 1}", ""), ("[1, 2]", ""), ("\"ok\"", "ok")] {
        let r = p.act(&format!(r#"{{"set": "text", "value": {value}}}"#));
        assert!(r.contains("\"ok\":true"), "{r}");
        // the panels still draw
        field_image(&mut p);
        // a tap still focuses, typing still types (after the text the field shows)
        tap_field(&mut p, 700.0);
        p.text_input("ab");
        assert_eq!(text_of(&mut p), format!("{shows}ab"), "after text = {value}");
        assert!(p.key("escape"));
    }
    // a megabyte of agent text: the field keeps the first MAX_TEXT bytes
    let r = p.act(&format!(r#"{{"set": "text", "value": "{}"}}"#, "字".repeat(400_000)));
    assert!(r.contains("\"ok\":true"), "{}", &r[..r.len().min(200)]);
    tap_field(&mut p, 40.0);
    let t = text_of(&mut p);
    assert!(t.len() <= 2000 && t.chars().all(|c| c == '字'), "{} bytes", t.len());
    // the agent action checks its parameter
    assert!(p.act(r#"{"action": "type", "params": {"text": 5}}"#).contains("text must be a string"));
    assert!(p.act(r#"{"action": "type", "params": {}}"#).contains("text must be a string"));
    assert_eq!(p.handler_errors, 0);
    p.shutdown();
}

#[test]
fn large_input_is_refused_not_a_handler_error() {
    captured::install();
    let mut p = load();
    tap_field(&mut p, 40.0);
    p.text_input("kept");
    // a 3 MB commit and a 4 MB paste: refused by size before any string work
    p.text_input(&"x".repeat(3 << 20));
    p.paste(&"y".repeat(4 << 20));
    let r = p.act(&format!(r#"{{"action": "type", "params": {{"text": "{}"}}}}"#, "z".repeat(20_000)));
    assert!(r.contains("refused"), "{}", &r[..r.len().min(200)]);
    // fifty-odd submits at once: refused as well
    p.text_input(&"line\n".repeat(60));
    assert_eq!(text_of(&mut p), "kept");
    let log = log_of(&mut p);
    for want in ["input too long: 3145728 bytes (at most 16384)", "input too long: 4194304 bytes (at most 16384)", "input too long: 20000 bytes (at most 16384)", "input refused: 60 lines (at most 50)"] {
        assert!(log.iter().any(|l| l == want), "{want} in {log:?}");
    }
    // the field still fills up to its own limit
    p.text_input(&"w".repeat(1990));
    p.text_input("0123456789");
    assert!(log_of(&mut p).iter().any(|l| l == "field full: 2000 bytes"));
    assert_eq!(text_of(&mut p).len(), 4 + 1990);
    assert_eq!(p.handler_errors, 0);

    // ctrl+shift+c copies more than the Android clipboard takes: the host refuses it
    assert!(p.key("ctrl+shift+c"));
    match p.take_request() {
        Some(PageRequest::Copy(t)) => {
            assert_eq!(t.len(), 3 << 20);
            let e = crate::requests::check_copy(&t).unwrap_err();
            assert!(e.contains("copy refused"), "{e}");
        }
        other => panic!("{other:?}"),
    }
    p.shutdown();
}

#[test]
fn typed_text_stays_out_of_page_log() {
    captured::install();
    let mut p = load();
    tap_field(&mut p, 40.0);
    p.text_input("SECRET-7f3a");
    p.ime_preedit("SECRET-9c1d");
    p.ime_preedit("");
    assert!(p.key("enter"));
    p.paste("SECRET-2b8e");
    // the on-screen log shows what was typed (shortened when long) ...
    let screen = log_of(&mut p);
    assert!(screen.iter().any(|l| l == "text: SECRET-7f3a"), "{screen:?}");
    assert!(screen.iter().any(|l| l == "ime: SECRET-9c1d"), "{screen:?}");
    p.text_input(&"é".repeat(100));
    let long = log_of(&mut p).into_iter().find(|l| l.starts_with("text: éé")).expect("long text line");
    assert!(long.ends_with("… (200 bytes)") && long.len() < 120, "{long}");
    // ... page.log (logcat on Android) only lengths
    let lines = captured::lines();
    assert!(lines.iter().any(|l| l.ends_with("text: 11 bytes")), "{lines:?}");
    assert!(lines.iter().any(|l| l.ends_with("enter: 11 bytes")), "{lines:?}");
    assert!(lines.iter().all(|l| !l.contains("SECRET-")), "{lines:?}");
    p.shutdown();
}

/// The debug-only probe page (app/src/debug/assets/pages/host-probe): each
/// button makes a request that used to crash or break the Android host;
/// here they go through the host's own routing ([`crate::requests::route`])
/// and caret rules ([`crate::view`]).
#[test]
fn the_host_probe_requests_are_refused_or_contained() {
    use crate::requests::{route, FileDialogs, Route, MAX_NAME};
    use crate::view;

    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("app/src/debug/assets/pages/host-probe");
    let pkg = Package::from_dir(&dir).expect("probe package");
    let mut p = ScriptPage::load(&pkg, &Natives::new(), text(), wake()).expect("probe loads");
    let bounds = p.spec().bounds;
    // the probe buttons: 2 columns of 350 x 84, 20 apart, from y = 90
    let tap = |p: &mut ScriptPage, i: usize| {
        let (col, row) = ((i - 1) % 2, (i - 1) / 2);
        let r = p.pointer_down(col as f32 * 370.0 + 175.0, 90.0 + row as f32 * 104.0 + 42.0);
        assert_eq!(r, PointerResponse::Handled, "probe {i}");
    };
    let mut dialogs = FileDialogs::default();
    let next = |p: &mut ScriptPage, dialogs: &mut FileDialogs| route(p.take_request().expect("a request"), dialogs);

    // 1, 2: copy 3 MB is refused with a notice, 200 KB goes to the clipboard
    tap(&mut p, 1);
    assert!(matches!(next(&mut p, &mut dialogs), Route::Notice(m) if m.contains("copy refused")));
    tap(&mut p, 2);
    assert!(matches!(next(&mut p, &mut dialogs), Route::Copy(t) if t.len() == 200 * 1024));

    // 3, 4: carets at 1e39 and 1e30 are refused by the runtime now (no
    // focus at all); were one to get through, the host would not follow it
    for (i, what) in [(3, "caret at 1e39"), (4, "caret at 1e30")] {
        tap(&mut p, i);
        assert_eq!(p.text_focus(), None, "probe {i}");
        assert!(log_of(&mut p).contains(&format!("{what}: refused by the runtime")), "{:?}", log_of(&mut p));
    }
    assert!(!view::revealable(anypage_engine::core::Rect::new(10.0, 1e30, 2.0, 30.0), bounds));
    // 5: a caret on the page is followed
    tap(&mut p, 5);
    let caret = p.text_focus().expect("focus");
    assert!(view::revealable(caret, bounds), "probe 5: {caret:?}");
    tap(&mut p, 6);
    assert_eq!(p.text_focus(), None);

    // 7: two opens at once: the second fails at once, the first waits for its picker
    tap(&mut p, 7);
    let Route::Open { token, .. } = next(&mut p, &mut dialogs) else { panic!("first open") };
    match next(&mut p, &mut dialogs) {
        Route::Answer(id, r) => p.host_result(id, r),
        other => panic!("{other:?}"),
    }
    assert!(log_of(&mut p).iter().any(|l| l == "open 2: failed: a file dialog is already open"), "{:?}", log_of(&mut p));
    assert!(dialogs.finish(token).is_some());

    // 8: a 1 MB save name reaches the picker as 255 bytes, extension kept
    tap(&mut p, 8);
    match next(&mut p, &mut dialogs) {
        Route::Save { token, name, size } => {
            assert!(name.len() == MAX_NAME && name.ends_with(".txt") && size == 5, "{} bytes", name.len());
            dialogs.finish(token);
        }
        other => panic!("{other:?}"),
    }

    // 9, 10: 5000 filters and a 1 MB filter fail the request with a short message
    for i in [9, 10] {
        tap(&mut p, i);
        match next(&mut p, &mut dialogs) {
            Route::Answer(id, r) => p.host_result(id, r),
            other => panic!("{other:?}"),
        }
    }
    let log = log_of(&mut p);
    assert!(log.iter().any(|l| l == "open 5000 filters: failed: open_file: 5000 filters, at most 32"), "{log:?}");
    assert!(log.iter().any(|l| l.starts_with("open 1 MB filter: failed: open_file: bad filter") && l.len() < 200), "{log:?}");
    assert!(dialogs.is_empty());
    assert_eq!(p.handler_errors, 0);
    p.shutdown();
}

#[test]
fn the_field_draws_caret_text_and_composition() {
    let mut p = load();
    let idle = field_image(&mut p);
    assert!(near(px(&idle, 10, 48), FIELD_BG, 2), "{:?}", px(&idle, 10, 48));
    // no caret and no accent border before focus
    assert_eq!(count_in(&idle, 0, 720, 0, 96, |c| near(c, ACCENT, 30)), 0);

    tap_field(&mut p, 40.0);
    p.text_input("Hello");
    let typed = field_image(&mut p);
    let caret_x = (p.text_focus().unwrap().x - FIELD.0).round() as u32;
    // the caret is a 3-unit accent bar at the focus rectangle
    assert!(near(px(&typed, caret_x + 1, 48), ACCENT, 8), "caret at {caret_x}: {:?}", px(&typed, caret_x + 1, 48));
    // glyph pixels left of the caret, none right of it
    let bright = |c: [u8; 3]| c.iter().all(|v| *v > 150) && !near(c, ACCENT, 30);
    let ink_left = count_in(&typed, 20, caret_x, 20, 76, bright);
    let ink_right = count_in(&typed, caret_x + 6, 700, 20, 76, bright);
    assert!(ink_left > 60, "text drawn: {ink_left}");
    assert_eq!(ink_right, 0);

    p.ime_preedit("wor");
    let composing = field_image(&mut p);
    let after = (p.text_focus().unwrap().x - FIELD.0).round() as u32;
    assert!(after > caret_x + 20);
    // composition in the preedit colour, underlined, between the old and new caret
    let pre = count_in(&composing, caret_x + 1, after, 10, 86, |c| near(c, PRE, 40));
    assert!(pre > 40, "preedit pixels: {pre}");
    assert!(near(px(&composing, after + 1, 48), ACCENT, 8));
    write_png(&composing, "android-text-field-composing.png");
    write_png(&typed, "android-text-field.png");
    p.shutdown();
}

